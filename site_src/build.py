#!/usr/bin/env python3
"""Build the portal source tree from the suite's own files.

Nothing on a page is typed twice. Lesson prose lives in site_src/lessons/, every run
panel renders from results/records/*.json, and every file offered for download is
copied from the path the record names, so a page cannot drift from the artifact it
teaches.

Counts obey the same rule: {{stat: gate.fail}} and friends are tallied from the records
at build time rather than written into the prose, and {{predict: <record>}} reads
an exercise's answer out of the same file the lesson is quizzing the reader
about. Figures like these move on every
re-recording, and hand-written ones had twice fallen behind the corpus they described.

    python3 site_src/build.py     # site_src/ + benchmarks/ + results/ -> portal/
    mkdocs build --strict         # portal/ -> _site/

Benchmark task pages are generated from each benchmarks/**/benchmark.yml. They are
reached from the benchmarks index and from search rather than from the nav, because
50 nav entries would bury the lessons.
"""
import collections
import functools
import hashlib
import json
import pathlib
import re
import shutil
import sys

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "runner"))
import ld_to_st  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "site_src"
OUT = ROOT / "portal"
RECORDS = ROOT / "results" / "records"
BENCH = ROOT / "benchmarks"

BANNER = ("<!-- Generated by site_src/build.py from the files it names. "
          "Edit the source under site_src/, never this file. -->")
DIRECTIVE = re.compile(r"^\{\{\s*(\w+)\s*:\s*(.*?)\s*\}\}[ \t]*$", re.M)

KIND = {".ld": "ladder program, PLCopen XML", ".xml": "ladder program, PLCopen XML",
        ".st": "structured text", ".yaml": "property file",
        ".yml": "benchmark metadata", ".md": "notes", ".sh": "run script",
        ".smv": "nuXmv model", ".json": "run record",
        ".il": "instruction list"}
LANG = {".ld": "xml", ".xml": "xml", ".yaml": "yaml", ".yml": "yaml",
        ".st": "text", ".sh": "bash", ".json": "json"}
VERDICT = {True: "SAFE", False: "VIOLATION"}

STATS = {"pages": 0, "files": 0}


def write(path, title, body):
    """One generated page.

    The title is explicit because every page here is an index.md, and MkDocs falls
    back to the filename whenever it cannot read an H1 as the document's first
    element. The banner that warns against editing is exactly such an element.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    front = f"---\ntitle: {json.dumps(title)}\n---\n\n{BANNER}\n\n"
    path.write_text(front + body.rstrip("\n") + "\n", encoding="utf-8")
    STATS["pages"] += 1


def page_title(text, default):
    """The H1 a hand-written page already carries."""
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return default


def digest(path):
    """Short sha256, so a reader can check the file they downloaded is the one verified."""
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def fence(text, lang="", indent=0):
    """A fenced block, indented so it can sit inside a tab or a collapsed block."""
    pad = " " * indent
    body = "\n".join((pad + line).rstrip() for line in text.rstrip("\n").splitlines())
    return f"{pad}```{lang}\n{body}\n{pad}```"


def is_plcopen(path):
    """True when a .ld holds PLCopen XML rather than the textual ladder DSL.

    Both spellings use the extension, because ESBMC selects its LD front end from it,
    but only one of them is XML. Labelling by suffix alone told readers that a file of
    `XIC(Btn)` lines was PLCopen, and highlighted it as XML.
    """
    try:
        with path.open(encoding="utf-8", errors="replace") as handle:
            return handle.read(256).lstrip().startswith("<?xml")
    except OSError:
        return True


def kind_of(path):
    """What a reader is about to download."""
    if path.suffix == ".ld" and not is_plcopen(path):
        return "ladder program, textual DSL"
    return KIND.get(path.suffix, "file")


def lang_of(path):
    """The highlighter for a file, which the textual DSL does not share with XML."""
    if path.suffix == ".ld" and not is_plcopen(path):
        return "text"
    return LANG.get(path.suffix, "text")


def offer(paths, dest_dir, link_prefix="files"):
    """Copy files next to the page that teaches them and tabulate the downloads.

    The copy always lands in <page>/files/. The link may need a different spelling,
    because MkDocs resolves it against the source file's directory, and a top-level
    page sits one level above the directory it is served from.

    Two sources can share a basename (two benchmarks each with a props.yaml, offered
    by separate {{files: ...}} calls on the same page). A plain name-keyed copy would
    let the second silently overwrite the first. When an existing destination file
    has different content than the one about to be written, the new copy is
    disambiguated with its parent directory name instead.
    """
    rows = ["| file | what it is | size | sha256 |", "|---|---|---|---|"]
    for src in paths:
        name = src.name
        dest = dest_dir / "files" / name
        if dest.exists() and digest(dest) != digest(src):
            name = f"{src.parent.name}_{src.name}"
            dest = dest_dir / "files" / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        STATS["files"] += 1
        size = src.stat().st_size / 1024.0
        rows.append(f"| [`{name}`]({link_prefix}/{name}) | {kind_of(src)} "
                    f"| {size:.1f} KB | `{digest(src)}` |")
    return "\n".join(rows)


ONES = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine",
        "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen",
        "seventeen", "eighteen", "nineteen"]
TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty",
        "ninety"]


def spell(n):
    """A count as English, for prose that would rather not open on a digit."""
    if n < 20:
        return ONES[n]
    if n < 100:
        return TENS[n // 10] + ("-" + ONES[n % 10] if n % 10 else "")
    if n < 1000:
        rest = f" {spell(n % 100)}" if n % 100 else ""
        return f"{ONES[n // 100]} hundred{rest}"
    return str(n)


def read_properties(path):
    """The property list of one props.yaml."""
    return yaml.safe_load(path.read_text(encoding="utf-8"))["properties"]


def props_path(folder, meta):
    """The property file a benchmark names, resolved beside it.

    A syntax pair shares one file, so this can point into a sibling task's directory.
    """
    return folder / meta["properties_file"]


@functools.lru_cache(maxsize=1)
def property_catalog():
    """Every property in the catalog, grouped by kind, read from the files themselves.

    A kind's task count is smaller than its property count wherever one task pairs a
    safety claim with the witness that explains its violation.
    """
    kinds = {}
    for path in sorted(BENCH.glob("*/*/benchmark.yml")):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        props = read_properties(props_path(path.parent, meta))
        for prop in props:
            kinds.setdefault(prop["kind"], {"properties": 0, "tasks": 0})["properties"] += 1
        for kind in {prop["kind"] for prop in props}:
            kinds[kind]["tasks"] += 1
    return kinds


@functools.lru_cache(maxsize=1)
def corpus_stats():
    """Every figure the prose quotes, counted from the sources at build time.

    These move whenever the corpus is re-recorded, and a page that states them by hand
    drifts away from the records it links to. That happened twice before this existed.
    """
    stat = collections.Counter()
    for path in RECORDS.glob("*.json"):
        rec = json.loads(path.read_text(encoding="utf-8"))
        stat["records.total"] += 1
        for run in rec["runs"].values():
            stat["runs.total"] += 1
            if rec.get("route") == "via-c":
                stat["runs.viac"] += 1
                continue
            stat["runs.ladder"] += 1
            gate = (run.get("encoding") or {}).get("gate")
            stat[f"gate.{gate}"] += 1
            if gate == "fail":
                stat[f"gate.fail.{run['verdict'].lower()}"] += 1

    parts = yaml.safe_load((SRC / "lessons.yml").read_text(encoding="utf-8"))["parts"]
    stat["lessons.parts"] = len(parts)
    stat["lessons.count"] = sum(len(part["lessons"]) for part in parts)

    domains, llb_tasks, llb_variants, cited = set(), 0, 0, set()
    discriminator_tasks = 0
    for path in sorted(BENCH.glob("*/*/benchmark.yml")):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        stat["benchmarks.tasks"] += 1
        domains.add(meta.get("domain"))
        props = props_path(path.parent, meta)
        cited.add(props.resolve())
        for prop in read_properties(props):
            stat["props.total"] += 1
            stat[f'props.{prop["kind"]}'] += 1
        variants = meta.get("variants") or [meta]
        stat["benchmarks.programs"] += len(variants)
        tags = set(meta.get("tags") or [])
        if "llb" in tags:
            llb_tasks += 1
            llb_variants += len(variants)
        if "discriminator" in tags:
            discriminator_tasks += 1
    for extra in sorted(BENCH.glob("*/*/*.yaml")):
        # a property file no benchmark names exists to teach a lesson, not to be run
        if extra.resolve() not in cited:
            stat["props.teaching"] += len(read_properties(extra))
    stat["benchmarks.domains"] = len(domains)
    stat["llb.tasks"] = llb_tasks
    stat["llb.programs"] = llb_variants
    stat["benchmarks.discriminator"] = discriminator_tasks
    # a gate failure the tool announced (it refused the file) against one it did not
    stat["gate.fail.silent"] = stat["gate.fail"] - stat["gate.fail.error"]
    return stat


def render_stat(match):
    """{{stat: gate.fail}} or {{stat: gate.fail|words}}, counted rather than typed."""
    name, _, form = match.group(1).partition("|")
    stats = corpus_stats()
    if name not in stats:
        raise SystemExit(f"unknown statistic {{{{stat: {name}}}}}")
    value = stats[name]
    if form == "words":
        return spell(value)
    if form == "Words":
        return spell(value).capitalize()
    return str(value)


def render_files(arg, ctx):
    """{{files: a/b.ld | a/props.yaml}}

    MkDocs resolves the link against the page's URL, so "files/x" is right whether
    the page is portal/x.md or portal/lessons/x/index.md, as long as the copies land
    beside where the page is served from.
    """
    paths = [ROOT / p.strip() for p in arg.split("|") if p.strip()]
    return offer(paths, ctx["dir"], ctx.get("link_prefix", "files"))


def render_code(arg, _ctx):
    """{{code: a/b.ld}}, collapsed so a long file never crowds the prose."""
    parts = [p.strip() for p in arg.split("|")]
    src = ROOT / parts[0]
    lang = parts[1] if len(parts) > 1 else lang_of(src)
    size = src.stat().st_size / 1024.0
    block = fence(src.read_text(encoding="utf-8"), lang, indent=4)
    return f'??? example "{parts[0]} ({kind_of(src)}, {size:.1f} KB)"\n\n{block}'


def render_show(arg, _ctx):
    """{{show: a/props.yaml}} for a file short enough to read in place."""
    src = ROOT / arg.strip()
    body = src.read_text(encoding="utf-8").rstrip("\n")
    return f'```{lang_of(src)} title="{arg.strip()}"\n{body}\n```'


def render_citation(arg, _ctx):
    """{{citation: CITATION.cff}} so the citation block cannot drift from the file."""
    cff = yaml.safe_load((ROOT / arg.strip()).read_text(encoding="utf-8"))
    title = " ".join(cff["title"].split())
    names = "; ".join(f'{a["given-names"]} {a["family-names"]}' for a in cff["authors"])
    rows = ["| | |", "|---|---|", f"| title | {title} |", f"| authors | {names} |",
            f'| version | {cff["version"]} |', f'| license | {cff["license"]} |']
    for ident in cff.get("identifiers", []):
        doi, note = ident["value"], ident["description"].lower()
        rows.append(f"| DOI | [{doi}](https://doi.org/{doi}) ({note}) |")
    authors = " and ".join(f'{a["family-names"]}, {a["given-names"]}' for a in cff["authors"])
    key = cff["authors"][0]["family-names"].lower() + cff["version"].replace(".", "")
    bib = "\n".join([f"@misc{{{key},", f"  title   = {{{title}}},",
                     f"  author  = {{{authors}}},", "  year    = {2026},",
                     f'  doi     = {{{cff["doi"]}}},',
                     f'  version = {{{cff["version"]}}},',
                     "  note    = {Benchmark suite artifact}", "}"])
    abstract = " ".join(cff["abstract"].split())
    return "\n".join(rows) + "\n\n" + abstract + "\n\n" + fence(bib, "bibtex")


def render_coverage(_arg, _ctx):
    """{{coverage: benchmarks}} tallies the catalog by language at build time."""
    rows = {}
    for path in sorted((ROOT / "benchmarks").glob("*/*/benchmark.yml")):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        tasks, variants = rows.get(meta.get("language", "unspecified"), (0, 0))
        rows[meta["language"]] = (tasks + 1, variants + len(meta.get("variants", [])))
    out = ["| language | tasks | variants |", "|---|---|---|"]
    out += [f"| {lang} | {t} | {v} |" for lang, (t, v) in sorted(rows.items())]
    out.append(f"| total | {sum(t for t, _ in rows.values())} "
               f"| {sum(v for _, v in rows.values())} |")
    return "\n".join(out)


def render_properties(arg, _ctx):
    """{{properties: catalog}} tallies the catalog's property kinds at build time.

    {{properties: schema}} sets the same tally beside the vocabulary the schema declares,
    so a kind that is spelled but never used cannot pass unnoticed.
    """
    catalog = property_catalog()
    if arg.strip() == "schema":
        schema = json.loads((ROOT / "schema" / "properties.schema.json")
                            .read_text(encoding="utf-8"))
        declared = schema["$defs"]["property"]["properties"]["kind"]["enum"]
        rows = ["| kind in the schema | properties in the catalog |", "|---|---|"]
        rows += [f'| `{kind}` | {catalog.get(kind, {}).get("properties", 0) or "none"} |'
                 for kind in declared]
        return "\n".join(rows)
    rows = ["| kind | properties | tasks carrying one |", "|---|---|---|"]
    rows += [f'| `{kind}` | {row["properties"]} | {row["tasks"]} |' for kind, row
             in sorted(catalog.items(), key=lambda kv: -kv[1]["properties"])]
    rows.append(f'| total | {sum(r["properties"] for r in catalog.values())} '
                f'| {corpus_stats()["benchmarks.tasks"]} |')
    return "\n".join(rows)


def tool_label(run):
    """Both local builds answer 8.4.0, so the commit is what identifies a column."""
    tool = run.get("tool") or {}
    version = tool.get("version") or "?"
    return f'{version} `{tool["commit"]}`' if tool.get("commit") else version


def tabs(pairs):
    """Material content tabs, one per build."""
    out = []
    for label, body in pairs:
        out += [f'=== "{label}"\n', fence(body, "text", indent=4), ""]
    return "\n".join(out)


def generator_line(rec):
    """Name the Beremiz and MatIEC that produced the C, when the record carries them.

    A via-C verdict depends on the translation, so a panel that shows only the ESBMC
    commit is under-reporting what the reader is being asked to trust.
    """
    chain = rec.get("toolchain")
    if not chain:
        return []
    parts = []
    for name, label in (("beremiz", "Beremiz"), ("matiec", "MatIEC")):
        state = chain.get(name) or {}
        if not state.get("commit"):
            continue
        marked = state["commit"] + (", patched" if state.get("dirty") else "")
        parts.append(f"{label} `{marked}`")
    if not parts:
        return []
    return [f"Translated by {' and '.join(parts)}.\n"]


def render_predict(arg, _ctx):
    """{{predict: g_conveyor_interlock__bomb}} asks the reader before showing the record.

    The answer is read out of results/records rather than written into the lesson, so an
    exercise cannot come to disagree with the run it is quizzing the reader about. The
    prompt after a pipe overrides the default question.
    """
    name, _, prompt = arg.partition("|")
    rec = json.loads((RECORDS / (name.strip() + ".json")).read_text(encoding="utf-8"))
    runs = rec["runs"]
    gated = rec.get("route") != "via-c"
    program = pathlib.Path(rec["program"]).name
    prompt = prompt.strip() or (
        f"`{program}` carries the property below. Will the "
        + ("ladder front end" if gated else "C route")
        + " report `SAFE` or `VIOLATION`"
        + (", and does the ingestion gate pass?" if gated else "?"))

    head = "| build | verdict | expected |" + (" ingestion gate |" if gated else "")
    rule = "|---|---|---|" + ("---|" if gated else "")
    rows = []
    for label, run in runs.items():
        row = f"| {label} | `{run['verdict']}` | `{rec['expected_verdict']}` |"
        if gated:
            row += f" {run['encoding']['gate']} |"
        rows.append(row)

    out = ['!!! question "Predict the verdict"', "", f"    {prompt}", "",
           '??? success "Answer"', ""]
    out += ["    " + line for line in [head, rule, *rows]]
    out.append("")
    return "\n".join(out)


def render_record(arg, _ctx):
    """{{record: interlock_viol}} renders results/records/interlock_viol.json in full."""
    rec = json.loads((RECORDS / (arg.strip() + ".json")).read_text(encoding="utf-8"))
    runs = rec["runs"]
    commands = {label: run["command"] for label, run in runs.items()}
    when = rec.get("recorded_at")
    out = []

    if len(set(commands.values())) == 1:
        out += [f"Recorded {when}. Every build ran the same command.\n",
                fence(next(iter(commands.values())), "text"), ""]
    if rec.get("route") == "via-c":
        solver = {run.get("solver_command") for run in runs.values() if run.get("solver_command")}
        if len(solver) == 1:
            out += ["which generates the C below and hands it to ESBMC as:\n",
                    fence(next(iter(solver)), "text"), ""]
        out += generator_line(rec)
    else:
        out += [f"Recorded {when}.\n", tabs(list(commands.items()))]

    gated = rec.get("route") != "via-c"
    header = "| build | ESBMC | verdict | expected | outcome |"
    header += " ingestion gate |" if gated else ""
    out += [header + " cpu |", "|---|---|---|---|---|" + ("---|" if gated else "") + "---|"]
    for label, run in runs.items():
        row = (f"| {label} | {tool_label(run)} | `{run['verdict']}` "
               f"| `{rec['expected_verdict']}` | {run['status']} |")
        if gated:
            row += f" {run['encoding']['gate']} |"
        out.append(row + f" {run['cpu_time_s']:.3f} s |")
    out.append("")

    proofs = [f"`{label}` found its solution by {run['proof']}."
              for label, run in runs.items() if run.get("proof")]
    if proofs:
        out.append("\n".join(proofs) + "\n")

    if rec.get("route") == "via-c":
        out += ["**What ESBMC was given.** The harness the adapter generated, with the "
                "property written over the variables MatIEC emitted.\n",
                fence(rec.get("generated_c", "").rstrip(), "c")]
    else:
        out += ["**What the front end encoded.** The scan body as the solver receives it, "
                "branch guards kept. An assignment-only view hides the guards and makes a "
                "guarded accumulator read as a constant.\n",
                tabs([(label, "\n".join(run["encoding"]["scan_body"]))
                      for label, run in runs.items()])]

    traces = [(label, run["counterexample"]) for label, run in runs.items()
              if run.get("counterexample")]
    if traces:
        out += ["**Counterexample.** ESBMC's own output. A trace long enough to need it "
                "is elided in the middle, and the omission is marked and counted where it "
                "happens.\n", tabs(traces)]
    return "\n".join(out)


HANDLERS = {"files": render_files, "code": render_code, "show": render_show,
            "record": render_record, "citation": render_citation,
            "coverage": render_coverage, "properties": render_properties,
            "predict": render_predict}


STAT = re.compile(r"\{\{\s*stat\s*:\s*([\w.|]+)\s*\}\}")


def expand(text, ctx):
    """Replace every {{directive: argument}} line, and every inline {{stat: ...}}."""
    text = STAT.sub(render_stat, text)
    def sub(match):
        name = match.group(1)
        if name not in HANDLERS:
            raise SystemExit(f'{ctx["name"]}: unknown directive {{{{{name}}}}}')
        return HANDLERS[name](match.group(2), ctx)
    return DIRECTIVE.sub(sub, text)


def build_lessons():
    """The curated path, grouped into parts that the sidebar can collapse."""
    parts = yaml.safe_load((SRC / "lessons.yml").read_text(encoding="utf-8"))["parts"]
    page = ["# Lessons\n",
            "Each lesson runs one program past ESBMC and shows what came back, including "
            "what the front end encoded before the solver saw it. Work through a part in "
            "order; each lesson assumes the one before it.\n"]
    for part in parts:
        for lesson in part["lessons"]:
            dest = OUT / "lessons" / lesson["slug"]
            body = (SRC / "lessons" / (lesson["slug"] + ".md")).read_text(encoding="utf-8")
            ctx = {"dir": dest, "name": lesson["slug"]}
            write(dest / "index.md", f'{lesson["number"]} {lesson["title"]}',
                  f'# {lesson["title"]}\n\n{expand(body, ctx)}')
        page += [f'## {part["title"]}\n', part["blurb"].strip() + "\n",
                 "| lesson | what it shows |", "|---|---|"]
        page += [f'| **{les["number"]}** [{les["title"]}]({les["slug"]}/index.md) '
                 f'| {les["summary"]} |' for les in part["lessons"]]
        page.append("")
    write(OUT / "lessons" / "index.md", "Lessons", "\n".join(page))
    return parts


def build_nav(parts):
    """Emit the nav mkdocs.yml inherits, so a new lesson needs one edit, not two."""
    lessons = [{"Overview": "lessons/index.md"}]
    for part in parts:
        lessons.append({part["title"]: [
            {f'{les["number"]} {les["title"]}': f'lessons/{les["slug"]}/index.md'}
            for les in part["lessons"]]})
    foundations = [
        {"The five languages": "languages.md"},
        {"The properties we prove": "properties.md"},
        {"How ESBMC-PLC works": "how-esbmc-plc-works.md"},
        {"The tools underneath": "the-tools-underneath.md"},
        {"Ladder logic bombs": "ladder-logic-bombs.md"}]
    nav = [{"Home": "index.md"},
           {"Foundations": foundations},
           {"Ladder to structured text": "ld-to-st.md"},
           {"Reproducing": "reproducing.md"},
           {"Benchmarks": "benchmarks/index.md"},
           {"Lessons": lessons},
           {"Citing": "citing.md"}]
    (ROOT / "nav.generated.yml").write_text(
        "# Generated by site_src/build.py. mkdocs.yml inherits it.\n"
        + yaml.safe_dump({"nav": nav}, sort_keys=False, allow_unicode=True),
        encoding="utf-8")


def program_index():
    """Which recorded runs, if any, used a given program file.

    A record names the .ld copy the run was made against, because ESBMC picks its
    front end from the extension while the catalog stores graphical programs as
    .xml. Both spellings map to the same task.
    """
    index, seen = {}, {}
    for path in sorted(RECORDS.glob("*.json"), key=lambda q: (len(q.stem), q.stem)):
        rec = json.loads(path.read_text(encoding="utf-8"))
        program = rec["program"]
        # record_all.py and the per-lesson records can cover the same pair; the
        # shorter name wins, because that is the one a lesson cites.
        key = (program, rec["properties_file"], rec.get("route", "ld"))
        if key in seen:
            continue
        seen[key] = path.stem
        index.setdefault(program, []).append(path.stem)
        if program.endswith(".ld"):
            index.setdefault(program[:-3] + ".xml", []).append(path.stem)
    return index


def record_line(name):
    """One recorded run, summarised: what was asked and what each build answered."""
    rec = json.loads((RECORDS / (name + ".json")).read_text(encoding="utf-8"))
    verdicts = ", ".join(f"{label} `{run['verdict']}`" for label, run in rec["runs"].items())
    props = pathlib.Path(rec["properties_file"]).name
    # A failed gate means the property's variables were never assigned in the scan
    # loop, so that build's verdict is about a program missing the part under test.
    dropped = [label for label, run in rec["runs"].items()
               if run.get("encoding", {}).get("gate", "pass") != "pass"]
    note = f" — ingestion gate failed on {', '.join(dropped)}" if dropped else ""
    route = " via C" if rec.get("route") == "via-c" else ""
    return (f'- `{name}`{route} ({props}, expected `{rec["expected_verdict"]}`): '
            f"{verdicts}{note}")


def sibling_links(text, meta):
    """A benchmark README points at sibling directories; on the site those are pages."""
    def fix(match):
        name = match.group(1)
        target = meta["_dir"].parent / name / "benchmark.yml"
        return f"](../{name}/index.md)" if target.exists() else match.group(0)
    return re.sub(r"\]\(\.\./([A-Za-z0-9_]+)/\)", fix, text)


def claim_of(prop):
    """A property as a reader should read it, from whichever field carries it.

    Reachability inverts the usual reading, so the row says which way it is meant to be
    taken rather than leaving a bare expression that looks like a safety claim.
    """
    if prop.get("expression"):
        wrapped = f'`{prop["expression"]}`'
        return f"reachable: {wrapped}" if prop["kind"] == "reachability" else wrapped
    if prop.get("variables"):
        return "never true together: " + ", ".join(f"`{v}`" for v in prop["variables"])
    return "every scan completes"


def build_properties(meta):
    """What this task asks, from the file the runner hands ESBMC.

    A task page that lists only files and verdicts leaves the question itself off the
    page, and the question is the part a reviewer has to disagree with.
    """
    path = props_path(meta["_dir"], meta)
    rows = ["| id | kind | claim | requirement |", "|---|---|---|---|"]
    for prop in read_properties(path):
        why = " ".join(prop["justification"].split()).replace("|", "\\|")
        rows.append(f'| `{prop["id"]}` | `{prop["kind"]}` | {claim_of(prop)} | {why} |')
    named = path.resolve().relative_to(ROOT)
    return ["\n## What is proved\n",
            f"From `{named}`. What each kind claims, and what it becomes on either "
            "route, is on [The properties we prove](../../../properties.md).\n",
            "\n".join(rows)]


def ladder_as_st(files):
    """Structured text derived from each PLCopen LD file among a variant's files.

    Only `is_plcopen` files carry a ladder body to walk; the textual `.ld` DSL and
    non-ladder languages (FBD, SFC, IL, hand-written ST) have nothing to derive. A file
    that is PLCopen XML but carries no `<LD>` body (FBD- or SFC-only) is skipped too,
    since ld_to_st.translate returns "" for it.
    """
    pairs = []
    for path in files:
        if path.suffix not in (".ld", ".xml") or not is_plcopen(path):
            continue
        st = ld_to_st.translate(path)
        if st:
            pairs.append((path.name, st))
    return pairs


def build_benchmark(meta, recorded):
    """One task page, keyed by suite id, at /benchmarks/<domain>/<id>/."""
    source = meta.get("source", {})
    dest = OUT / "benchmarks" / meta["domain"] / meta["id"]
    rows = [("suite id", f'`{meta["id"]}`'), ("domain", meta["domain"]),
            ("language", meta.get("language", "")),
            ("difficulty", meta.get("difficulty", "")),
            ("validation status", meta.get("validation_status", "")),
            ("origin", source.get("origin", "")), ("license", source.get("license", ""))]
    if meta.get("syntax_pair_of"):
        rows.append(("syntax pair of", f'`{meta["syntax_pair_of"]}`'))
    body = ["| | |", "|---|---|"] + [f"| {name} | {value} |" for name, value in rows]
    if source.get("reference"):
        body.append(f'\n{source["reference"]}\n')

    body += build_properties(meta)

    body += ["\n## Variants\n",
             "| file | expected verdict | violates | ground truth |", "|---|---|---|---|"]
    for var in meta.get("variants", []):
        expected = VERDICT.get(var.get("expected_verdict"), var.get("expected_verdict"))
        method = var.get("ground_truth", {}).get("method", "")
        violated = ", ".join(f"`{p}`" for p in var.get("violated_properties", [])) or "none"
        body.append(f'| `{var["file"]}` | {expected} | {violated} | {method} |')

    files = sorted(p for p in meta["_dir"].iterdir() if p.is_file() and p.name != "README.md")
    body += ["\n## Files\n", offer(files, dest)]

    st_pairs = ladder_as_st(files)
    if st_pairs:
        body += ["\n## Structured text, derived\n",
                 "Read off the ladder graph by `runner/ld_to_st.py`: every rung's contacts "
                 "and coils rewritten as IEC 61131-3 assignments, in the same series/"
                 "parallel logic the PLCopen XML encodes. This is a reading aid, not a "
                 "second ground truth; ESBMC verifies the ladder program shown above, "
                 "never this rendering.\n", tabs(st_pairs)]

    readme = meta["_dir"] / "README.md"
    if readme.exists():
        body += ["\n## Notes\n", sibling_links(readme.read_text(encoding="utf-8"), meta)]

    runs = [name for var in meta.get("variants", []) for name in
            recorded.get(f'benchmarks/{meta["domain"]}/{meta["id"]}/{var["file"]}', [])]
    body.append("\n## Recorded runs\n")
    body.append("A task can carry two routes. `ld` is ESBMC's ladder front end reading the "
                "program directly. `via C` is the same solver reached through Beremiz and "
                "MatIEC, which is the only route that reaches ST, IL, FBD and SFC; see "
                "[How ESBMC-PLC works](../../../how-esbmc-plc-works.md).\n")
    body.append("\n".join(record_line(name) for name in sorted(set(runs))) if runs else
                "No ESBMC run is recorded against this task yet. The lessons carry the "
                "recorded runs; see [Reproducing](../../../reproducing.md) to make your own.")
    write(dest / "index.md", meta["id"],
          f'# {meta.get("name", meta["id"])}\n\n' + "\n".join(body))


def tally(metas, field):
    """How many tasks fall under each value of one metadata field."""
    counts = {}
    for meta in metas:
        key = meta.get(field, "unspecified")
        counts[key] = counts.get(key, 0) + 1
    return counts


def build_benchmarks():
    """The catalog. Every id here is a stable URL, so nothing may be renumbered."""
    recorded = program_index()
    metas = []
    for path in sorted((ROOT / "benchmarks").glob("*/*/benchmark.yml")):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        meta["_dir"] = path.parent
        metas.append(meta)
        build_benchmark(meta, recorded)

    domains = sorted({m["domain"] for m in metas})
    page = ["# Benchmarks\n",
            f"{len(metas)} tasks across {len(domains)} domains. A task's URL is its suite "
            "id and does not move, because published results cite it. The catalog "
            "tracks the working tree; the archived release carries its own counts, "
            "listed under [Citing](../citing.md).\n",
            "| language | tasks |", "|---|---|"]
    page += [f"| {k} | {v} |" for k, v in sorted(tally(metas, "language").items())]
    page += ["\n| validation status | tasks |", "|---|---|"]
    page += [f"| {k} | {v} |" for k, v in sorted(tally(metas, "validation_status").items())]

    for domain in domains:
        page += [f'\n## {domain.replace("_", " ")}\n',
                 "| id | name | language | difficulty | status |", "|---|---|---|---|---|"]
        for meta in sorted((m for m in metas if m["domain"] == domain), key=lambda m: m["id"]):
            page.append(f'| [`{meta["id"]}`]({domain}/{meta["id"]}/index.md) '
                        f'| {meta.get("name", "")} | {meta.get("language", "")} '
                        f'| {meta.get("difficulty", "")} '
                        f'| {meta.get("validation_status", "")} |')
    write(OUT / "benchmarks" / "index.md", "Benchmarks", "\n".join(page))
    return metas


def build_static():
    """Hand-written pages, plus anything already documented elsewhere in the repo."""
    for path in sorted((SRC / "pages").glob("*.md")):
        # a page at portal/x.md is served from /x/, so its downloads belong in
        # portal/x/files/ rather than at the site root
        ctx = {"dir": OUT / path.stem, "name": path.name,
               "link_prefix": f"{path.stem}/files"}
        text = path.read_text(encoding="utf-8")
        write(OUT / path.name, page_title(text, path.stem), expand(text, ctx))
    macos = ROOT / "docs" / "BUILD_MACOS.md"
    if macos.exists():
        text = macos.read_text(encoding="utf-8")
        write(OUT / "build-macos.md", "Building ESBMC on macOS", text)
    for css in (SRC / "stylesheets").glob("*.css"):
        dest = OUT / "stylesheets" / css.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(css, dest)
        STATS["files"] += 1
    for script in (SRC / "scripts").glob("*.js"):
        dest = OUT / "scripts" / script.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(script, dest)
        STATS["files"] += 1


def main():
    """Regenerate portal/ from scratch, so a deleted source page cannot linger."""
    shutil.rmtree(OUT, ignore_errors=True)
    parts = build_lessons()
    build_nav(parts)
    metas = build_benchmarks()
    build_static()
    print(f'portal: {STATS["pages"]} pages, {STATS["files"]} files, '
          f'{sum(len(p["lessons"]) for p in parts)} lessons, {len(metas)} benchmarks')
    return 0


if __name__ == "__main__":
    sys.exit(main())
