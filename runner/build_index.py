#!/usr/bin/env python3
"""Generate docs/INDEX.md from the benchmark metadata.

SUITE.yml and the index itself have named this script for months without it existing,
so the table was frozen at the v1.0.1 numbers while the tree grew past them. A count
written by hand goes stale on the next commit that adds a program; this one is derived.

    build_index.py            # rewrite docs/INDEX.md
    build_index.py --check    # exit 1 if the file is out of date, for CI
"""
import argparse
import collections
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
BENCH = ROOT / "benchmarks"
INDEX = ROOT / "docs" / "INDEX.md"
PORTAL = "https://pierredantas.github.io/esbmc-plc-benchmark-suite/benchmarks/"


def tasks():
    """Every benchmark, as (domain, language, id, variants, verdicts, difficulty, langs).

    `langs` is the language of each program variant, which is what the README and the
    portal count. A task carries one language label, so tallying tasks gives a smaller
    and different set of numbers for the same tree.
    """
    rows = []
    for path in sorted(BENCH.glob("*/*/benchmark.yml")):
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))
        variants = meta.get("variants") or [meta]
        verdicts = "/".join("SAFE" if v.get("expected_verdict") else "VIOL"
                            for v in variants)
        langs = [v.get("language") or meta["language"] for v in variants]
        rows.append((meta["domain"], meta["language"], meta["id"],
                     len(variants), verdicts, meta.get("difficulty", ""), langs))
    return sorted(rows)


def render(rows):
    """The index as Markdown, counts included, so nothing here is typed by hand."""
    langs = collections.Counter()
    variants = 0
    for row in rows:
        langs.update(row[6])
        variants += row[3]
    domains = len({row[0] for row in rows})
    mix = " · ".join(f"{n} {lang}" for lang, n in langs.most_common())

    out = [f"# Suite Index ({len(rows)} tasks / {variants} variants)",
           "",
           "Generated by `runner/build_index.py` from `benchmarks/**/benchmark.yml`. Run it "
           "after adding or removing a benchmark; do not edit this file by hand.",
           "",
           f"Composition by program variant: {mix}, across {domains} domains.",
           "",
           f"The [portal catalog]({PORTAL}) carries the same list with the recorded runs "
           "attached to each task.",
           "",
           "| domain | language | id | variants | verdicts | difficulty |",
           "|---|---|---|---|---|---|"]
    out += [f"| {row[0]} | {row[1]} | `{row[2]}` | {row[3]} | {row[4]} | {row[5]} |"
            for row in rows]
    return "\n".join(out) + "\n"


def main():
    """Write the index, or report that it has drifted."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 when the file is out of date")
    args = ap.parse_args()
    text = render(tasks())
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != text:
            print(f"{INDEX.relative_to(ROOT)} is out of date; run runner/build_index.py")
            return 1
        print(f"{INDEX.relative_to(ROOT)} is up to date")
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"{INDEX.relative_to(ROOT)}: {len(tasks())} tasks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
